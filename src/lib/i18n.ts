import { num, plural } from "./fmt";

export type Lang = "ar" | "en";

/**
 * A counted phrase in its four Arabic forms (1 / 2 / 3–10 / 11+). Only
 * `few` and `many` carry "{n}"; `one` and `two` are written out
 * ("نشاط واحد", "نشاطين"). English uses `one` for 1 and `many` otherwise,
 * and spells its `one`/`two` with the digit so both bundles hold the
 * same placeholders.
 */
export interface CountForms {
  /** For none at all, where "0 نشاط" is not a phrase anyone says. */
  zero?: string;
  one: string;
  two: string;
  few: string;
  many: string;
}

/** Picks the form for `n` and fills in the number. */
export function countText(lang: Lang, n: number, forms: CountForms): string {
  const form =
    lang === "en" ? (n === 0 && forms.zero ? forms.zero : n === 1 ? forms.one : forms.many) : plural(n, forms);
  return form.replace("{n}", num(n, lang));
}

